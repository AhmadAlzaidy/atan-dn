"""Write the paper tables (LaTeX + Markdown) from the result files of the pipeline. Never invents a number.

Inputs (all optional; a table whose inputs are missing is skipped and the missing files are logged):

* ``--report MISSION:MODEL=report.json``     (``evaluate.py`` / ``evaluate_baseline_scores.py``; repeatable) -> Table 1 rows
* ``--multi-seed MISSION=multi_seed_summary.json``  (``run_multi_seed.py``) -> extra "ATAN-DN, n seeds" rows, mean +/- std
* ``--ablation NAME=<study>_results.json``   (``run_ablation.py``) -> ablation table (kurtosis, Fisher criterion, F1, ...)
* ``--mask-params MISSION=mask_params.json`` (``train.py``) -> derived-parameter table (every numeric entry found)
* ``--complexity MISSION=complexity.json``   (``complexity.py``) -> complexity table and, if ``--project`` was used, the
  latency projection table
* ``--run-dir MISSION=DIR``  shortcut: adds ``DIR/report.json`` (model ATAN-DN), ``DIR/mask_params.json``,
  ``DIR/complexity.json`` and ``DIR/multi_seed_summary.json`` when they exist.

Table 1 style: Prec., Rec., FPR, FNR, F1, F0.5 of the chosen ``--level`` (``window``: window-level metrics, default;
``point``: point-wise rule A); mean +/- std (sample std as stored by the multi-seed runner) where seeds exist. Output
``<out-dir>/<table>.tex`` and ``.md``, plus ``tables.md`` with all Markdown tables.

Exit codes: 0 ok (also when tables were skipped for missing inputs), 2 invalid arguments.
"""
from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path
from typing import Any, Sequence

from _common import ScriptError, run_cli

log = logging.getLogger("atandn.scripts.make_tables")

METRICS = (("precision", "Prec."), ("recall", "Rec."), ("fpr", "FPR"), ("fnr", "FNR"), ("f1", "F1"), ("f0_5", "F0.5"))
LEVELS = {
    "window": ("window_metrics", "window_"),
    "point": ("pointwise_metrics_rule_A", "point_"),
    "pa": ("point_adjusted_metrics", "pa_"),
    "point_adjusted": ("point_adjusted_metrics", "pa_"),
}
ABLATION_DEFAULT = ("kurtosis_norm", "fisher_latent", "window_f1")
_ABL_LABELS = {"kurtosis_norm": ("Kurtosis", "Kurtosis"), "fisher_latent": ("Fisher J", "Fisher $J$"),
               "window_f1": ("F1", "$F_1$"), "window_f0_5": ("F0.5", "$F_{0.5}$"), "window_fpr": ("FPR", "FPR"),
               "window_precision": ("Prec.", "Prec."), "window_recall": ("Rec.", "Rec."),
               "point_f1": ("Point F1", "Point $F_1$"), "n_params": ("Params", "Params")}


# ---------------------------------------------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------------------------------------------
def _tex(s: Any) -> str:
    return str(s).replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def _num(v: Any, decimals: int, std: Any = None, md: bool = False) -> str:
    if v is None or (isinstance(v, float) and v != v):
        return "--"
    txt = f"{float(v):.{decimals}f}"
    if std is not None:
        txt += (" ± " if md else r" $\pm$ ") + f"{float(std):.{decimals}f}"
    return txt


def _read_json(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None


def _latex_table(header: Sequence[str], rows: Sequence[Sequence[str]], caption: str, label: str, source: str,
                 align: str | None = None, rules_before: Sequence[int] = ()) -> str:
    align = align or "l" + "c" * (len(header) - 1)
    out = [f"% generated by scripts/make_tables.py from: {source}", r"\begin{table}[!h]", r"\centering",
           rf"\caption{{{caption}}}", rf"\label{{{label}}}", r"\footnotesize", rf"\begin{{tabular}}{{{align}}}", r"\toprule",
           " & ".join(rf"\textbf{{{h}}}" for h in header) + r" \\", r"\midrule"]
    for i, r in enumerate(rows):
        if i in rules_before:
            out.append(r"\midrule")
        out.append(" & ".join(r) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(out) + "\n"


def _md_table(header: Sequence[str], rows: Sequence[Sequence[str]], title: str, note: str = "") -> str:
    lines = [f"### {title}", "", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines) + "\n" + (f"\n{note}\n" if note else "")


# ---------------------------------------------------------------------------------------------------------------
# individual tables; each returns (header, rows_tex, rows_md, caption, source) or None
# ---------------------------------------------------------------------------------------------------------------
def table_results(reports: list[tuple[str, str, Path]], multi: dict[str, Path], level: str,
                  missing: list[str]) -> dict | None:
    """Table 1: one row per (mission, model), plus mean +/- std rows from multi-seed summaries."""
    key, prefix = LEVELS[level]
    rows_t: list[list[str]] = []
    rows_m: list[list[str]] = []
    rules: list[int] = []
    sources: list[str] = []
    missions: list[str] = []
    for m, _, _ in reports:
        if m not in missions:
            missions.append(m)
    for m in multi:
        if m not in missions:
            missions.append(m)
    for mission in missions:
        entries: list[tuple[str, list[str], list[str]]] = []
        for m, model, path in reports:
            if m != mission:
                continue
            rep = _read_json(path)
            if rep is None:
                missing.append(f"report {path} (Table 1: {mission} {model})")
                continue
            if key not in rep:
                missing.append(f"report {path} has no '{key}'")
                continue
            vals = rep[key]
            entries.append((model, [_num(vals.get(k), 4) for k, _ in METRICS], [_num(vals.get(k), 4, md=True) for k, _ in METRICS]))
            sources.append(str(path))
        if mission in multi:
            summ = _read_json(multi[mission])
            if summ is None:
                missing.append(f"multi-seed summary {multi[mission]} (Table 1: {mission})")
            else:
                st = summ.get("summary", {})
                n = max((v.get("n", 0) for v in st.values() if isinstance(v, dict)), default=0)
                cells_t, cells_m = [], []
                for k, _ in METRICS:
                    s = st.get(prefix + k)
                    cells_t.append(_num(s["mean"], 4, s["std"]) if s else "--")
                    cells_m.append(_num(s["mean"], 4, s["std"], md=True) if s else "--")
                entries.append((f"ATAN-DN, {n} seeds, mean ± std" if n else "ATAN-DN, seeds", cells_t, cells_m))
                sources.append(str(multi[mission]))
        if entries:
            rules.append(len(rows_t))
            for model, ct, cm in entries:
                rows_t.append([_tex(mission.upper()), _tex(model)] + ct)
                rows_m.append([mission.upper(), model] + cm)
    if not rows_t:
        return None
    header = ["Mission", "Model"] + [lab for _, lab in METRICS]
    if level in ("pa", "point_adjusted"):
        cap = ("Comparative Performance Evaluation (point-adjusted PA event scoring matching ESA-ADB Supplementary Table 9; "
               "evaluated at the F1-optimal threshold $\\tau^\\ast$ after Stage 3 operational masking; mean $\\pm$ sample std over seeds where stated).")
    else:
        cap = (f"Detection results ({level}-level metrics; threshold chosen on the validation block of the "
               "training split; mean $\\pm$ sample std over seeds where stated).")
    return {"name": "table1_results", "header": header, "tex": rows_t, "md": rows_m, "caption": cap, "label": "tab:final_results",
            "source": ", ".join(sources), "align": "l l " + "c" * len(METRICS), "rules": rules[1:]}


def table_ablation(abl: dict[str, Path], metrics: Sequence[str], missing: list[str]) -> list[dict]:
    """Ablation tables (one per study) from ``run_ablation.py`` result JSONs."""
    out = []
    for name, path in abl.items():
        data = _read_json(path)
        if data is None:
            missing.append(f"ablation results {path} (study {name})")
            continue
        summary = data.get("summary") or {}
        meta = data.get("meta") or {}
        order = list(meta.get("variants") or summary.keys())
        header = ["Variant"] + [_ABL_LABELS.get(m, (m, _tex(m)))[1] for m in metrics] + ["Seeds"]
        header_md = ["Variant"] + [_ABL_LABELS.get(m, (m, m))[0] for m in metrics] + ["Seeds"]
        rows_t, rows_m = [], []
        for v in order:
            st = summary.get(v)
            if not st:
                continue
            ct, cm, n = [], [], 0
            for m in metrics:
                s = st.get(m)
                dec = 0 if m == "n_params" else 3
                multi = bool(s) and s.get("n", 1) > 1
                ct.append(_num(s["mean"], dec, s["std"] if multi else None) if s else "--")
                cm.append(_num(s["mean"], dec, s["std"] if multi else None, md=True) if s else "--")
                n = max(n, s.get("n", 0) if s else 0)
            rows_t.append([_tex(v)] + ct + [str(n)])
            rows_m.append([v] + cm + [str(n)])
        if rows_t:
            out.append({"name": f"table_ablation_{name}", "header": header, "header_md": header_md, "tex": rows_t, "md": rows_m,
                        "caption": f"Ablation study {_tex(name)}: feature statistics and window-level F1 (mean $\\pm$ std over seeds).",
                        "label": f"tab:ablation_{name}", "source": str(path)})
    return out


def table_derived(mask: dict[str, Path], missing: list[str]) -> dict | None:
    """Derived-parameter table: every numeric scalar entry of the ``mask_params.json`` files (rows) per mission (columns)."""
    cols: dict[str, dict[str, Any]] = {}
    for mission, path in mask.items():
        d = _read_json(path)
        if d is None:
            missing.append(f"mask parameters {path} ({mission})")
            continue
        cols[mission] = {k: v for k, v in d.items() if isinstance(v, (int, float)) and not isinstance(v, bool)}
        for k, v in d.items():
            if isinstance(v, dict):                                  # nested blocks (e.g. transition_zones): scalar members
                for k2, v2 in v.items():
                    if isinstance(v2, (int, float)) and not isinstance(v2, bool):
                        cols[mission][f"{k}.{k2}"] = v2
    if not cols:
        return None
    keys = sorted({k for c in cols.values() for k in c})
    missions = list(cols)
    fmt = lambda v: "--" if v is None else (str(v) if isinstance(v, int) else f"{v:.4g}")
    rows_t = [[_tex(k)] + [fmt(cols[m].get(k)) for m in missions] for k in keys]
    rows_m = [[k] + [fmt(cols[m].get(k)) for m in missions] for k in keys]
    return {"name": "table_derived_params", "header": ["Parameter"] + [m.upper() for m in missions], "tex": rows_t, "md": rows_m,
            "caption": "Parameters derived automatically from the training split (Stage 2).", "label": "tab:derived_params",
            "source": ", ".join(str(mask[m]) for m in missions)}


def table_complexity(cx: dict[str, Path], missing: list[str]) -> list[dict]:
    """Complexity table (parameters, FLOPs, measured latency) and the OBC projection table of the first file that has one."""
    data = {}
    for m, p in cx.items():
        d = _read_json(p)
        if d is None:
            missing.append(f"complexity json {p} ({m})")
        else:
            data[m] = (d, p)
    out = []
    if data:
        rows_t, rows_m = [], []
        for m, (d, _) in data.items():
            par, fl = d.get("parameters", {}), d.get("flops_per_window", {})
            lat = d.get("latency_with_decoder", {})
            lat2 = d.get("latency_without_decoder", {})
            cells = [f"{par.get('with_decoder', float('nan')):,}", f"{par.get('without_decoder', float('nan')):,}",
                     f"{fl.get('decoder_inverse_solve', {}).get('total', float('nan')):.3e}",
                     f"{fl.get('without_decoder', {}).get('total', float('nan')):.3e}",
                     _num(lat.get("mean_ms"), 3), _num(lat2.get("mean_ms"), 3)]
            rows_t.append([_tex(m.upper())] + cells)
            rows_m.append([m.upper()] + cells)
        out.append({"name": "table_complexity",
                    "header": ["Mission", "Params (full)", "Params (no decoder)", "FLOPs (full)", "FLOPs (no decoder)",
                               "Latency full (ms)", "Latency no dec. (ms)"],
                    "tex": rows_t, "md": rows_m,
                    "caption": "Model complexity: parameters, analytic FLOPs per window and measured latency (batch 1).",
                    "label": "tab:complexity", "source": ", ".join(str(p) for _, p in data.values())})
        for m, (d, p) in data.items():
            proj = d.get("projection")
            if not proj:
                continue
            rows_t = [[_tex(r["platform"]), f"{r['peak_gflops']:g}", f"{r['efficiency']:g}", f"{r['latency_ms']:.4g}",
                       f"{r['fps']:.4g}", _tex(r["viability"])] for r in proj["platforms"]]
            rows_m = [[r["platform"], f"{r['peak_gflops']:g}", f"{r['efficiency']:g}", f"{r['latency_ms']:.4g}",
                       f"{r['fps']:.4g}", r["viability"]] for r in proj["platforms"]]
            out.append({"name": "table_latency_projection",
                        "header": ["Platform", "Peak GFLOPS", "Efficiency", "Latency (ms)", "FPS", "Viability"],
                        "tex": rows_t, "md": rows_m,
                        "caption": (f"Theoretical latency projection of {proj['flops']:.3e} FLOPs "
                                    f"({_tex(proj['flops_key'])}); compute-bound estimate, hardware values from "
                                    f"{_tex(proj['hardware_file'])} (not re-verified)."),
                        "label": "tab:latency_compact", "source": str(p)})
            break
    return out


# ---------------------------------------------------------------------------------------------------------------
# driver
# ---------------------------------------------------------------------------------------------------------------
def make_tables(out_dir: str | Path, reports: Sequence[tuple[str, str, Path]] = (), multi: dict[str, Path] | None = None,
                ablation: dict[str, Path] | None = None, mask_params: dict[str, Path] | None = None,
                complexity: dict[str, Path] | None = None, level: str = "window",
                ablation_metrics: Sequence[str] = ABLATION_DEFAULT) -> dict[str, Any]:
    """Write all tables that have inputs; returns ``{"written": [paths], "skipped": [reasons]}``."""
    if level not in LEVELS:
        raise ValueError(f"level must be one of {sorted(LEVELS)}")
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    missing: list[str] = []
    tables: list[dict] = []
    skipped: list[str] = []

    if reports or multi:
        t = table_results(list(reports), multi or {}, level, missing)
        if t:
            tables.append(t)
        else:
            skipped.append("table1_results: no usable report / multi-seed file")
    else:
        skipped.append("table1_results: no --report / --multi-seed given")
    if ablation:
        ts = table_ablation(ablation, ablation_metrics, missing)
        tables.extend(ts)
        if not ts:
            skipped.append("table_ablation: no usable ablation results")
    else:
        skipped.append("table_ablation: no --ablation given")
    if mask_params:
        t = table_derived(mask_params, missing)
        if t:
            tables.append(t)
        else:
            skipped.append("table_derived_params: no usable mask_params.json")
    else:
        skipped.append("table_derived_params: no --mask-params given")
    if complexity:
        ts = table_complexity(complexity, missing)
        tables.extend(ts)
        if not ts:
            skipped.append("table_complexity: no usable complexity json")
    else:
        skipped.append("table_complexity: no --complexity given")

    written: list[Path] = []
    md_all: list[str] = []
    for t in tables:
        tex = _latex_table(t["header"], t["tex"], t["caption"], t["label"], t["source"], t.get("align"), t.get("rules", ()))
        md = _md_table(t.get("header_md", t["header"]), t["md"], t["caption"].replace("$\\pm$", "±").replace("$", ""))
        tex_p, md_p = out / f"{t['name']}.tex", out / f"{t['name']}.md"
        tex_p.write_text(tex, encoding="utf-8")
        md_p.write_text(md, encoding="utf-8")
        written += [tex_p, md_p]
        md_all.append(md)
        log.info("wrote %s (+ .md)", tex_p)
    if md_all:
        (out / "tables.md").write_text("\n".join(md_all), encoding="utf-8")
        written.append(out / "tables.md")
    for m in missing:
        log.warning("MISSING input, skipped: %s", m)
    for s in skipped:
        log.warning("table skipped: %s", s)
    return {"written": written, "skipped": skipped + missing}


def _kv(items: Sequence[str], what: str, with_model: bool = False) -> list:
    out = []
    for it in items:
        if "=" not in it:
            raise ScriptError(f"{what} expects NAME=PATH, got '{it}'", 2)
        k, v = it.split("=", 1)
        if with_model:
            if ":" not in k:
                raise ScriptError(f"{what} expects MISSION:MODEL=PATH, got '{it}'", 2)
            m, model = k.split(":", 1)
            out.append((m, model, Path(v)))
        else:
            out.append((k, Path(v)))
    return out


def build_parser() -> argparse.ArgumentParser:
    """Argument parser of ``make_tables.py``."""
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out-dir", required=True, type=Path, help="directory for the .tex / .md files")
    p.add_argument("--report", action="append", default=[], metavar="MISSION:MODEL=PATH", help="report.json (repeatable)")
    p.add_argument("--multi-seed", action="append", default=[], metavar="MISSION=PATH", help="multi_seed_summary.json")
    p.add_argument("--ablation", action="append", default=[], metavar="NAME=PATH", help="<study>_results.json")
    p.add_argument("--mask-params", action="append", default=[], metavar="MISSION=PATH", help="mask_params.json")
    p.add_argument("--complexity", action="append", default=[], metavar="MISSION=PATH", help="complexity.json")
    p.add_argument("--run-dir", action="append", default=[], metavar="MISSION=DIR", help="a run directory of the pipeline")
    p.add_argument("--level", default="window", choices=sorted(LEVELS), help="metrics of Table 1 (default: window)")
    p.add_argument("--ablation-metrics", nargs="+", default=list(ABLATION_DEFAULT), help="columns of the ablation table")
    p.add_argument("--log-level", default="INFO", choices=["DEBUG", "INFO", "WARNING", "ERROR"])
    return p


def run(args: argparse.Namespace) -> None:
    """Collect the inputs from the command line and write the tables."""
    reports = _kv(args.report, "--report", with_model=True)
    multi = dict(_kv(args.multi_seed, "--multi-seed"))
    abl = dict(_kv(args.ablation, "--ablation"))
    mask = dict(_kv(args.mask_params, "--mask-params"))
    cx = dict(_kv(args.complexity, "--complexity"))
    for mission, d in _kv(args.run_dir, "--run-dir"):
        for fname, target in (("report.json", None), ("mask_params.json", mask), ("complexity.json", cx),
                              ("multi_seed_summary.json", multi)):
            f = d / fname
            if not f.is_file():
                log.info("run dir %s has no %s", d, fname)
                continue
            if target is None:
                reports.insert(0, (mission, "ATAN-DN", f))
            else:
                target[mission] = f
    res = make_tables(args.out_dir, reports, multi, abl, mask, cx, args.level, args.ablation_metrics)
    log.info("%d files written, %d notes", len(res["written"]), len(res["skipped"]))


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point; returns the process exit code."""
    return run_cli(build_parser, run, argv)


if __name__ == "__main__":
    raise SystemExit(main())
